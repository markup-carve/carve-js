// Writes src/package-info.ts: the package version, the spec version and pin, and the node types of the pinned
// ast-schema.json. `npm run build` runs it first.
//   node scripts/generate-package-info.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { wrapJson } from './wrap-literal.ts'

const root = join(import.meta.dirname, '..')
const read = (path: string): string => readFileSync(join(root, path), 'utf8')

interface SchemaNode { properties: { children: { items: { oneOf: { $ref: string }[] } } } }

/** The text of src/package-info.ts for `package.json`, `data/spec-pin.json` and `data/ast-schema.json`. */
export function generatePackageInfo(packageJson: string, specPin: string, astSchema: string): string {
  const { version } = JSON.parse(packageJson) as { version: string }
  const { commit } = JSON.parse(specPin) as { commit: string }
  const defs = (JSON.parse(astSchema) as { $defs: Record<string, SchemaNode> }).$defs
  const types = (node: string): string[] => defs[node]!.properties.children.items.oneOf.map((entry) => entry.$ref.split('/').pop()!)
  return [
    '// Generated by scripts/generate-package-info.ts from package.json, data/spec-pin.json and data/ast-schema.json. Do not edit.',
    '',
    '/** The version of this package. */',
    `export const VERSION = ${JSON.stringify(version)}`,
    '',
    '/** The specification this engine implements, and the commit of markup-carve/carve it pins. */',
    `export const SPEC_VERSION: { readonly version: string, readonly commit: string } = Object.freeze({`,
    `  version: '0.2',`,
    `  commit: ${JSON.stringify(commit)},`,
    '})',
    '',
    '/** The node types of the pinned tree schema: those a document holds as blocks, and those a paragraph holds. */',
    'export const NODE_TYPES: { readonly block: readonly string[], readonly inline: readonly string[] } = Object.freeze({',
    ...wrapJson('block: Object.freeze(', types('document'), '),', '  '),
    ...wrapJson('inline: Object.freeze(', types('paragraph'), '),', '  '),
    '})',
    '',
  ].join('\n')
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(join(root, 'src/package-info.ts'),
    generatePackageInfo(read('package.json'), read('data/spec-pin.json'), read('data/ast-schema.json')))
}

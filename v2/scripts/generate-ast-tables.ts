// C2-A-026, C2-A-133: writes the node slot and result tables from the specification data.
//   node v2/scripts/generate-ast-tables.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

interface ResultField {
  field: string
  when?: string
}

interface ResultData {
  nodes: Record<string, ResultField[]>
}

interface SlotData {
  nodes: Record<string, string[]>
}

function table<T>(name: string, nodes: Record<string, T[]>, item: (value: T) => string): string[] {
  const lines = [`export const ${name}: ReadonlyMap<string, readonly ${name === 'NODE_SLOTS' ? 'string' : 'ResultField'}[]> = new Map([`]
  for (const [type, values] of Object.entries(nodes)) {
    lines.push(`  [${JSON.stringify(type)}, [`, ...values.map((value) => `    ${item(value)},`), '  ]],')
  }
  return [...lines, '])']
}

/** C2-A-026, C2-A-133: the two generated tables. */
export function generateAstTables(resultsJson: string, slotsJson: string): string {
  const results = JSON.parse(resultsJson) as ResultData
  const slots = JSON.parse(slotsJson) as SlotData
  return [
    '// C2-A-026, C2-A-133: generated by scripts/generate-ast-tables.ts. Do not edit.',
    '',
    'export interface ResultField {',
    '  field: string',
    '  when?: string',
    '}',
    '',
    ...table('AST_RESULTS', results.nodes, (value) => JSON.stringify(value)),
    '',
    ...table('NODE_SLOTS', slots.nodes, (value) => JSON.stringify(value)),
    '',
  ].join('\n')
}

if (process.argv[1] === import.meta.filename) {
  const root = join(import.meta.dirname, '..')
  const read = (name: string): string => readFileSync(join(root, 'data', name), 'utf8')
  writeFileSync(join(root, 'src/ast-tables.ts'), generateAstTables(read('ast-results.json'), read('node-slots.json')))
}
